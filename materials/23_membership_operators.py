# 35. Membership Operators = Check if an element is in a sequence

name = "Rahfi"
print("f" in name)
print("f" not in name)

grades = {"A": 90, "B": 80, "C": 70, "D": 60}
print("A" in grades)
print("A" not in grades)

students = ["John", "Jane", "Mark", "Alice"]
print("John" in students)
print("John" not in students)

if "John" in students:
    print("John is in the class")
else:
    print("John is not in the class")